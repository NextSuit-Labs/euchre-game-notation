const fs = require("fs");
const path = require("path");
const Ajv = require("ajv");
const addFormats = require("ajv-formats");
const standaloneCode = require("ajv/dist/standalone").default;

const repoRoot = __dirname;
const schemaDir = path.join(repoRoot, "schemas");
const generatedDir = path.join(repoRoot, "src", "generated");

const egnSchema = require(path.join(schemaDir, "egn-schema-v1.json"));
const emnSchema = require(path.join(schemaDir, "emn", "emn-schema-v1.json"));

const dealSchema = {
  $schema: "http://json-schema.org/draft-07/schema#",
  definitions: egnSchema.definitions,
  ...egnSchema.properties.deals.items.oneOf[0],
};

function generateHeader(title) {
  return [
    "/* eslint-disable */",
    "// @ts-nocheck",
    "// This file is auto-generated by generate-validators.js.",
    "// Do not edit it manually; regenerate with `npm run generate:validators`.",
    `// Pre-compiled standalone ${title} validator (CSP-safe, zero runtime JIT/eval).`,
    "",
  ].join("\n");
}

function buildValidators() {
  if (!fs.existsSync(generatedDir)) {
    fs.mkdirSync(generatedDir, { recursive: true });
  }

  // 1. Generate EGN & Deal standalone validators
  console.log("Compiling EGN & Deal JSON schemas to standalone code...");
  const egnAjv = new Ajv({ code: { source: true, esm: true } });
  addFormats(egnAjv);
  egnAjv.addSchema(egnSchema, "egn");
  egnAjv.addSchema(dealSchema, "deal");

  const egnCode = standaloneCode(egnAjv, {
    validateEgn: "egn",
    validateDeal: "deal",
  });

  const egnOutputPath = path.join(generatedDir, "validators.ts");
  fs.writeFileSync(egnOutputPath, generateHeader("EGN & Deal") + egnCode, "utf8");
  console.log(`✓ Successfully generated "${egnOutputPath}"`);

  // 2. Generate EMN standalone validator
  console.log("Compiling EMN JSON schema to standalone code...");
  const emnAjv = new Ajv({ code: { source: true, esm: true } });
  addFormats(emnAjv);
  emnAjv.addSchema(egnSchema, "../egn-schema-v1.json");
  emnAjv.addSchema(egnSchema, "egn-schema-v1.json");
  emnAjv.addSchema(emnSchema, "emn");

  const emnCode = standaloneCode(emnAjv, {
    validateEmn: "emn",
  });

  const emnOutputPath = path.join(generatedDir, "emn-validators.ts");
  fs.writeFileSync(emnOutputPath, generateHeader("EMN") + emnCode, "utf8");
  console.log(`✓ Successfully generated "${emnOutputPath}"`);
}

if (require.main === module) {
  buildValidators();
}

module.exports = { buildValidators };
